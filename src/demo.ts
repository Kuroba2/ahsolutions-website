// Explicitly fictional, used only when a visitor chooses to load this example.
const fictionalBrief = `FICTIONAL SAMPLE — not a real customer request.\nA local appointment booking business wants a web app where customers can schedule and cancel appointments.\nCustomers should receive an email confirmation after booking.\nStaff need a dashboard to see appointments and mark attendance.\nThe client is considering calendar integration but has not selected a provider.\nThey hope to launch a pilot for one location before expanding.`;

function sentencesFromInput(raw: string): string[] {
  const lines = raw
    .replace(/\r/g, '\n')
    .split(/\n+|(?<=[.!?])\s+(?=[A-ZÀ-Ỹ0-9])/u)
    .map((s) => s.trim().replace(/^[\s\-•*\d.)]+/u, '').trim())
    .filter((s) => s.length > 24 && !/^fictional sample\b/i.test(s));
  const unique: string[] = [];
  for (const line of lines) {
    const normalized = line.toLowerCase().replace(/\W+/g, ' ');
    if (!unique.some((previous) => previous.toLowerCase().replace(/\W+/g, ' ') === normalized)) unique.push(line);
    if (unique.length === 8) break;
  }
  return unique;
}

function clarificationQuestions(text: string): string[] {
  const lowered = text.toLowerCase();
  const output = [
    'Who will use the product, and what are their highest-priority tasks?',
    'Which features are essential for the first release, and which can wait?',
    'How will the client measure success for the initial release?',
  ];
  const patterns: Array<[RegExp, string]> = [
    [/book|appoint|reserv|schedule|đặt lịch/i, 'What are the booking rules (availability, cancellations, time zones, and conflicts)?'],
    [/pay|checkout|billing|invoice|thanh toán/i, 'Which payment methods, billing rules, or providers need to be supported?'],
    [/login|account|role|permission|user|đăng nhập/i, 'What user roles exist and what can each role access?'],
    [/email|sms|notifi|thông báo/i, 'Which notifications are required, and when should they be sent?'],
    [/integrat|api|calendar|sync|tích hợp/i, 'Which external services or APIs must be integrated, and are credentials available?'],
    [/data|customer|privacy|personal|gdpr|dữ liệu/i, 'What information will be stored, who can access it, and how long should it be retained?'],
  ];
  for (const [pattern, question] of patterns) if (pattern.test(lowered)) output.push(question);
  if (!/deadline|timeline|week|month|launch|pilot|sprint|hạn|tháng|tuần/i.test(lowered)) {
    output.push('Is there a launch deadline or delivery schedule?');
  } else {
    output.push('Is the target launch date fixed, and which milestones must happen before it?');
  }
  return output.slice(0, 9);
}

function makeProposal(raw: string, extracted: string[], followups: string[]): string {
  const rawExcerpt = raw.trim().replace(/\r/g, '').slice(0, 1200);
  const bullets = (items: string[]) => items.map((s) => `- ${s.replace(/\n/g, ' ')}`).join('\n');
  return `# Project proposal — editable working outline\n\n> Generated by AH BriefFlow prototype v0.1 using simple browser-side rules, NOT Claude or another AI model. Review all content manually before sharing.\n\n## Original brief excerpt\n\n${rawExcerpt}${raw.trim().length > 1200 ? '\n\n[Excerpt truncated. Refer to original input.]' : ''}\n\n## Candidate requirements (quoted or lightly trimmed from brief)\n\n${bullets(extracted)}\n\n## Clarification questions (suggested by rules)\n\n${bullets(followups)}\n\n## Proposed scope\n\n- In-scope features: TBD after clarification\n- Out-of-scope features: TBD\n- Integrations: TBD\n- Data and security considerations: TBD\n\n## Deliverables and timeline\n\n- Deliverables: TBD\n- Timeline / estimates: TBD — do not commit without review\n\n## Human approval\n\n- [ ] Confirm requirements with the client\n- [ ] Verify assumptions, security and constraints\n- [ ] Approve scope, timeline and any pricing separately\n`;
}

function addItems(target: HTMLElement, data: string[]) {
  target.replaceChildren();
  for (const content of data) {
    const li = document.createElement('li');
    li.textContent = content; // Avoid HTML injection from visitor-controlled input.
    target.appendChild(li);
  }
}

function updateCount() { count.textContent = `${briefInput.value.length.toLocaleString()} / 12,000 characters`; }
briefInput.addEventListener('input', updateCount);
sampleButton.addEventListener('click', () => { briefInput.value = fictionalBrief; updateCount(); briefInput.focus(); });
clearButton.addEventListener('click', () => { briefInput.value = ''; proposal.value = ''; empty.hidden = false; results.hidden = true; status.textContent = ''; updateCount(); briefInput.focus(); });

analyzeButton.addEventListener('click', () => {
  const raw = briefInput.value.trim();
  if (raw.length < 60) {
    briefInput.setCustomValidity('Please enter at least 60 characters of project details.');
    briefInput.reportValidity();
    briefInput.setCustomValidity('');
    return;
  }
  const extracted = sentencesFromInput(raw);
  if (extracted.length === 0) {
    briefInput.setCustomValidity('Please include at least one full sentence with project details.');
    briefInput.reportValidity();
    briefInput.setCustomValidity('');
    return;
  }
  const followups = clarificationQuestions(raw);
  addItems(requirements, extracted);
  addItems(questions, followups);
  reqCount.textContent = `(${extracted.length})`;
  proposal.value = makeProposal(raw, extracted, followups);
  status.textContent = 'Draft created locally in your browser. Review before sharing.';
  empty.hidden = true;
  results.hidden = false;
});

copyButton.addEventListener('click', async () => {
  try { await navigator.clipboard.writeText(proposal.value); status.textContent = 'Draft copied to clipboard.'; }
  catch { status.textContent = 'Clipboard unavailable. Select and copy the text from the editor.'; }
});

downloadButton.addEventListener('click', () => {
  const file = new Blob([proposal.value], {type:'text/markdown;charset=utf-8'});
  const url = URL.createObjectURL(file);
  const link = document.createElement('a');
  link.href = url;
  link.download = 'ah-briefflow-proposal-draft.md';
  link.click();
  URL.revokeObjectURL(url);
  status.textContent = 'Markdown draft downloaded.';
});
updateCount();
